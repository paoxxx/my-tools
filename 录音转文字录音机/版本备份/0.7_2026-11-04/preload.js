const { contextBridge, ipcRenderer } = require('electron');
const inv = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);
contextBridge.exposeInMainWorld('api', {
  getSettings: inv('settings:get'),
  setSettings: inv('settings:set'),
  list: inv('rec:list'),
  get: inv('rec:get'),
  audioUrl: inv('rec:audioUrl'),
  audioBytes: inv('rec:audioBytes'),
  save: inv('rec:save'),
  transcribe: inv('rec:transcribe'),
  remove: inv('rec:remove'),
  copy: inv('copy'),
  share: inv('share'),
  exportFiles: inv('export'),
  pickExportDir: inv('pick:exportDir'),
  micAsk: inv('mic:ask'),
  openMicSettings: inv('mic:settings'),
  liveStart: inv('live:start'),
  liveStop: inv('live:stop'),
  liveChunk: (ab) => ipcRenderer.send('live:chunk', ab),
  attach: inv('rec:attach'),
  onLive: (fn) => ipcRenderer.on('live:text', (e, d) => fn(d)),
  hotkeyTest: inv('hotkey:test'),
  onHotkey: (fn) => ipcRenderer.on('hotkey', () => fn()),
  onProgress: (fn) => ipcRenderer.on('trans:progress', (e, d) => fn(d)),
});
