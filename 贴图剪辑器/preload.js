const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  probe: file => ipcRenderer.invoke('probe', file),
  pickVideo: () => ipcRenderer.invoke('pick-video'),
  createProject: videoPath => ipcRenderer.invoke('create-project', videoPath),
  extractAudio: args => ipcRenderer.invoke('extract-audio', args),
  saveProject: args => ipcRenderer.invoke('save-project', args),
  openProject: () => ipcRenderer.invoke('open-project'),
  toolsStatus: () => ipcRenderer.invoke('tools-status'),
  fontPath: () => ipcRenderer.invoke('font-path'),
  transcribe: args => ipcRenderer.invoke('transcribe', args),
  cancelTranscribe: () => ipcRenderer.invoke('cancel-transcribe'),
  loadSrt: args => ipcRenderer.invoke('load-srt', args),
  findSrt: videoPath => ipcRenderer.invoke('find-srt', videoPath),
  pickSrt: () => ipcRenderer.invoke('pick-srt'),
  importAssets: args => ipcRenderer.invoke('import-assets', args),
  makeProxy: args => ipcRenderer.invoke('make-proxy', args),
  assetPeaks: args => ipcRenderer.invoke('asset-peaks', args),
  pasteAsset: args => ipcRenderer.invoke('paste-asset', args),
  saveAssetBytes: args => ipcRenderer.invoke('save-asset-bytes', args),
  libRoots: () => ipcRenderer.invoke('lib-roots'),
  libAddRoot: () => ipcRenderer.invoke('lib-add-root'),
  libRemoveRoot: p => ipcRenderer.invoke('lib-remove-root', p),
  libList: dir => ipcRenderer.invoke('lib-list', dir),
  libWatch: dir => ipcRenderer.invoke('lib-watch', dir),
  onLibChanged: cb => ipcRenderer.on('lib-changed', (e, d) => cb(d)),
  exportDefaults: () => ipcRenderer.invoke('export-defaults'),
  exportPickFolder: args => ipcRenderer.invoke('export-pick-folder', args),
  exportEstimate: args => ipcRenderer.invoke('export-estimate', args),
  exportStart: args => ipcRenderer.invoke('export-start', args),
  exportCancel: () => ipcRenderer.invoke('export-cancel'),
  onExportProgress: cb => ipcRenderer.on('export-progress', (e, p) => cb(p)),
  showInFolder: p => ipcRenderer.invoke('show-in-folder', p),
  openFile: p => ipcRenderer.invoke('open-file', p),
  bgCache: args => ipcRenderer.invoke('bg-cache', args),
  bgStill: args => ipcRenderer.invoke('bg-still', args),
  bgBegin: args => ipcRenderer.invoke('bg-begin', args),
  bgFrame: args => ipcRenderer.invoke('bg-frame', args),
  bgEnd: args => ipcRenderer.invoke('bg-end', args),
  settingsGet: () => ipcRenderer.invoke('settings-get'),
  settingsSet: patch => ipcRenderer.invoke('settings-set', patch),
  cacheScan: () => ipcRenderer.invoke('cache-scan'),
  cacheClean: args => ipcRenderer.invoke('cache-clean', args),
  onTranscribeProgress: cb => ipcRenderer.on('transcribe-progress', (e, p) => cb(p)),
  pathForFile: file => webUtils.getPathForFile(file),
});
